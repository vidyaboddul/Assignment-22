import streamlit as st

st.set_page_config(
    page_title="Heart Disease Prediction",
    page_icon="❤️",
    layout="centered"
)

import pandas as pd
import joblib

# Load model, columns and encoders
model = joblib.load("heart_model.pkl")
columns = joblib.load("columns.pkl")
encoders = joblib.load("encoders.pkl")

st.sidebar.title("🩺 About Project")

st.sidebar.info("""
This Heart Disease Prediction System uses a
Machine Learning Logistic Regression model
to predict whether a patient is likely to
have heart disease based on medical data.
""")

st.sidebar.markdown("### 👨‍💻 Developed by")
st.sidebar.write("Vidya Boddul")

# Title
st.title("❤️ Heart Disease Prediction System")
st.write("Enter patient details below.")
col1, col2 = st.columns(2)

# Input Fields
age = st.number_input("Age", min_value=1, max_value=120, value=30)

sex = st.selectbox(
    "Sex",
    ["F", "M"]
)

chest_pain = st.selectbox(
    "Chest Pain Type",
    ["ASY", "ATA", "NAP", "TA"]
)

resting_bp = st.number_input(
    "Resting Blood Pressure",
    min_value=50,
    max_value=250,
    value=120
)

cholesterol = st.number_input(
    "Cholesterol",
    min_value=0,
    max_value=700,
    value=200
)

fasting_bs = st.selectbox(
    "Fasting Blood Sugar",
    [0, 1]
)

resting_ecg = st.selectbox(
    "Resting ECG",
    ["LVH", "Normal", "ST"]
)

max_hr = st.number_input(
    "Maximum Heart Rate",
    min_value=60,
    max_value=250,
    value=150
)

exercise_angina = st.selectbox(
    "Exercise Angina",
    ["N", "Y"]
)

oldpeak = st.number_input(
    "Oldpeak",
    min_value=0.0,
    max_value=10.0,
    value=1.0,
    step=0.1
)

st_slope = st.selectbox(
    "ST Slope",
    ["Down", "Flat", "Up"]
)
    # Predict Button
if st.button("Predict"):

    # Create DataFrame
    input_data = pd.DataFrame({
        "Age": [age],
        "Sex": [sex],
        "ChestPainType": [chest_pain],
        "RestingBP": [resting_bp],
        "Cholesterol": [cholesterol],
        "FastingBS": [fasting_bs],
        "RestingECG": [resting_ecg],
        "MaxHR": [max_hr],
        "ExerciseAngina": [exercise_angina],
        "Oldpeak": [oldpeak],
        "ST_Slope": [st_slope]
    })

    # Encode categorical columns
    categorical_columns = [
        "Sex",
        "ChestPainType",
        "RestingECG",
        "ExerciseAngina",
        "ST_Slope"
    ]

    for column in categorical_columns:
        input_data[column] = encoders[column].transform(input_data[column])

    # Arrange columns in the same order as training
    input_data = input_data[columns]

    # Prediction
    prediction = model.predict(input_data)
    prediction_probability = model.predict_proba(input_data)

    heart_disease_probability = prediction_probability[0][1] * 100
    no_heart_disease_probability = prediction_probability[0][0] * 100
    confidence = prediction_probability[0][prediction[0]] * 100

    # Result
    if prediction[0] == 1:
        st.error("❤️ Heart Disease Detected")
    else:
        st.success("💚 No Heart Disease Detected")

    st.info(f"Prediction Confidence: {confidence:.2f}%")
    st.progress(int(confidence))

    st.subheader("📊 Prediction Probability")
    st.write(f"❤️ Heart Disease: **{heart_disease_probability:.2f}%**")
    st.write(f"💚 No Heart Disease: **{no_heart_disease_probability:.2f}%**")

    st.warning(
        "⚠️ This prediction is generated by a Machine Learning model and is intended for educational purposes only. Please consult a qualified healthcare professional for a medical diagnosis."
    )